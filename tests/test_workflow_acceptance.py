"""Cross-cutting acceptance coverage for the Issue #20 workflow boundary.

The lower-level workflow tests exercise individual loader, graph, bounds,
artifact, executor, and CLI behaviors.  This module keeps the Issue's
acceptance criteria visible at the integration boundary:

* configuration alone changes the declared execution order;
* top-level and loop-body steps use one request contract;
* invalid configurations fail before a port or artifact root is reached;
* the bundled workflow remains characteristically compatible with the fixed
  workflow; and
* runner command resolution remains outside the declarative workflow.
"""

