    def test_declarative_workflow_does_not_contain_runner_commands(self) -> None:
        """AC-8: workflow structure and runner command resolution stay separate."""

        raw_config = json.loads(self.standard_config_path.read_text(encoding="utf-8"))

        def keys(value: object) -> list[str]:
            if isinstance(value, dict):
                result: list[str] = []
                for key, child in value.items():
                    result.append(key)
                    result.extend(keys(child))
                return result
            if isinstance(value, list):
                return [key for child in value for key in keys(child)]
            return []

        self.assertFalse(
            {"command", "command_template", "callable", "shell"} & set(keys(raw_config))
        )

        runner = RunnerConfig(name="codex", command_template=["codex", "exec", "-"])
        resolver = RunnerResolver({"codex": runner}, default_name="codex")
        adapter = RunnerResolverCapabilityAdapter(resolver)
        snapshot = adapter.snapshot("repository_issue")
        resolved = adapter.resolve("codex", phase="plan", step_name="plan")

        self.assertNotIn("command_template", snapshot.runners["codex"].as_dict())
        self.assertEqual(resolved.command_template, ["codex", "exec", "-"])
        self.assertIn("codex", default_capability_registry().runners)


